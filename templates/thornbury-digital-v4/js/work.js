function plate(item) {
  var el = document.createElement("div");
  el.className = "piece-plate gate";
  if (item.src) {
    el.classList.add("has-media");
    if (item.light) el.classList.add("light");
    var img = document.createElement("img");
    img.className = "plate-media";
    img.src = item.src;
    img.alt = "";
    img.draggable = false;
    img.setAttribute("draggable", "false");
    img.width = 1680;
    img.height = 1060;
    img.loading = "lazy";
    img.decoding = "async";
    if (item.op) img.style.setProperty("--op", item.op);
    el.appendChild(img);
    if (item.light) {
      var scrim = document.createElement("i");
      scrim.className = "scrim";
      scrim.setAttribute("aria-hidden", "true");
      el.appendChild(scrim);
    }
  }
  el.setAttribute("aria-hidden", "true");
  return el;
}

function copy(item, idx) {
  var wrap = document.createElement("div");
  wrap.className = "piece-copy";
  if (idx) {
    var n = document.createElement("p");
    n.className = "idx";
    n.textContent = idx;
    wrap.appendChild(n);
  }
  var h = document.createElement("h2");
  h.textContent = item.name;
  wrap.appendChild(h);
  return wrap;
}

function listed(item, idx) {
  var a = document.createElement("a");
  a.className = "piece";
  a.href = item.href || "work.html";
  a.setAttribute("aria-label", item.name);
  a.appendChild(plate(item));
  a.appendChild(copy(item, idx));
  return a;
}

export function mountPieces(root, opts) {
  if (!root) return;
  var home = !!(opts && opts.home);
  var skip = (opts && opts.skip) || [];
  var frag = document.createDocumentFragment();
  var items = WORK.filter(function (item) {
    return item.name && skip.indexOf(item.name) === -1;
  });
  if (home) items = items.slice(0, 14);
  items.forEach(function (item, i) {
    frag.appendChild(listed(item, String(i + 1).padStart(2, "0")));
  });
  root.replaceChildren(frag);
}

export function bindRail(root, hooks) {
  if (!root) return;
  hooks = hooks || {};
  var down = false;
  var pid = 0;
  var origin = 0;
  var originScroll = 0;
  var moved = 0;
  var pending = 0;
  var raf = 0;

  root.querySelectorAll("img").forEach(function (img) {
    img.draggable = false;
    img.setAttribute("draggable", "false");
  });
  root.addEventListener("dragstart", function (e) {
    e.preventDefault();
  }, true);

  function step() {
    var card = root.querySelector(".piece");
    return card ? Math.round(card.getBoundingClientRect().width + 18) : 220;
  }

  function apply() {
    raf = 0;
    if (!down) return;
    root.scrollLeft = originScroll - pending;
  }

  root.addEventListener("pointerdown", function (e) {
    if (e.pointerType === "touch") return;
    if (e.button !== 0) return;
    down = true;
    pid = e.pointerId;
    origin = e.clientX;
    originScroll = root.scrollLeft;
    moved = 0;
    pending = 0;
    try { root.setPointerCapture(pid); } catch (err) {}
    if (hooks.onHold) hooks.onHold();
  });

  function onMove(e) {
    if (!down || e.pointerId !== pid) return;
    var dx = e.clientX - origin;
    moved = Math.max(moved, Math.abs(dx));
    pending = dx;
    if (moved > 8) root.classList.add("is-drag");
    if (!raf) raf = requestAnimationFrame(apply);
  }

  function release(e) {
    if (!down || (e && e.pointerId !== pid)) return;
    down = false;
    if (raf) {
      cancelAnimationFrame(raf);
      raf = 0;
    }
    root.scrollLeft = originScroll - pending;
    root.classList.remove("is-drag");
    if (moved > 16) root.dataset.skipClick = "1";
    if (hooks.onRelease) hooks.onRelease();
  }

  root.addEventListener("pointermove", onMove);
  root.addEventListener("pointerup", release);
  window.addEventListener("pointerup", release);
  root.addEventListener("pointercancel", release);

  root.addEventListener("click", function (e) {
    if (root.dataset.skipClick === "1") {
      e.preventDefault();
      e.stopPropagation();
      delete root.dataset.skipClick;
    }
  }, true);

  root.addEventListener("keydown", function (e) {
    if (e.key === "ArrowRight" || e.key === "ArrowLeft") {
      e.preventDefault();
      root.scrollBy({ left: e.key === "ArrowRight" ? step() : -step(), behavior: "smooth" });
    }
  });
}
