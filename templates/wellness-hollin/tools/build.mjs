/* ---------- the trace: one session as a temperature line ---------- */
function trace() {
  const W = 900, Ht = 300, padL = 44, padB = 34, padT = 10;
  const x = (m) => padL + (m / H.session.total) * (W - padL - 6);
  const y = (t) => padT + (1 - t / 100) * (Ht - padT - padB);
  let d = '';
  tl.forEach((s, i) => { d += `${i ? 'L' : 'M'}${x(s.from).toFixed(1)} ${y(s.temp).toFixed(1)}L${x(s.to).toFixed(1)} ${y(s.temp).toFixed(1)}`; });
  const zones = tl.filter((s) => s.cls === 'hot').map((s) => `<rect class="zone" x="${x(s.from).toFixed(1)}" y="${padT}" width="${(x(s.to) - x(s.from)).toFixed(1)}" height="${(Ht - padT - padB).toFixed(1)}"/>`).join('');
  const ticksY = [S.plunge.temp, S.rest.temp, S.rinse.temp, S.hot.temp];
  const TP = { [S.plunge.temp]: 'stage.plunge.temp', [S.rest.temp]: 'stage.rest.temp', [S.rinse.temp]: 'stage.rinse.temp', [S.hot.temp]: 'stage.hot.temp' };
  const gy = ticksY.map((t) => `<line x1="${padL}" x2="${W}" y1="${y(t).toFixed(1)}" y2="${y(t).toFixed(1)}"/>`).join('');
  const ly = ticksY.map((t) => `<text x="${padL - 10}" y="${(y(t) + 4).toFixed(1)}" text-anchor="end"><tspan data-bake="${TP[t]}">${t}</tspan>°</text>`).join('');
  const lx = [0, 30, 60, H.session.total].map((m) => `<text x="${x(m).toFixed(1)}" y="${Ht - 8}" text-anchor="${m === 0 ? 'start' : m === H.session.total ? 'end' : 'middle'}">${m === H.session.total ? `<tspan data-bake="session.total">${m}</tspan>` : m} min</text>`).join('');
  return `<figure class="trace reveal">
  <svg viewBox="0 0 ${W} ${Ht}" role="img" aria-labelledby="trace-cap" preserveAspectRatio="xMidYMid meet">
    <g>${zones}</g><g class="grid">${gy}</g><g class="axis">${ly}${lx}</g>
    <path class="path" data-trace pathLength="1" d="${d}"/>
  </svg>
  <figcaption id="trace-cap">One session, ${b('session.total')} minutes. Arrive and change (${b('session.arrive')} min), then ${b('session.rounds')} rounds of the hot room (${b('stage.hot.temp')} °C, ${b('stage.hot.min')} min), the rinse (${b('stage.rinse.temp')} °C, ${b('stage.rinse.min')} min), the plunge (${b('stage.plunge.temp')} °C, ${b('stage.plunge.min')} min) and the rest room (${b('stage.rest.temp')} °C, ${b('stage.rest.min')} min), then ${b('session.leave')} minutes to shower and dress. Shaded: time in the heat.</figcaption>
</figure>`;
}

