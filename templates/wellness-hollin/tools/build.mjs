/* ---------- helpers ---------- */
const get = (path) => path.split('.').reduce((o, k) => (o == null ? undefined : o[k]), H);
const fmt = (v, f) => (f === '1' ? Number(v).toFixed(1) : String(v));
/* b(): a baked number. */
const b = (path, f) => {
  const v = get(path);
  if (v === undefined) throw new Error('no data at ' + path);
  return `<span data-bake="${path}"${f ? ` data-bake-fmt="${f}"` : ''}>${fmt(v, f)}</span>`;
};
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function webpSize(file) {
  const buf = readFileSync(file);
  const chunk = buf.toString('ascii', 12, 16);
  if (chunk === 'VP8X') return [1 + buf.readUIntLE(24, 3), 1 + buf.readUIntLE(27, 3)];
  if (chunk === 'VP8 ') return [buf.readUInt16LE(26) & 0x3fff, buf.readUInt16LE(28) & 0x3fff];
  if (chunk === 'VP8L') { const n = buf.readUInt32LE(21); return [1 + (n & 0x3fff), 1 + ((n >> 14) & 0x3fff)]; }
  throw new Error('unknown webp ' + file);
}
const KIND = { hero: ['1920', '1080'], wide: ['1400', '800'], tall: ['900', '600'] };
/* pic(): responsive AVIF + WebP picture with real intrinsic size. */
function pic(name, kind, alt, sizes, opts = {}) {
  const [big, small] = KIND[kind];
  const [w, h] = webpSize(join(ROOT, `img/${name}-${small}.webp`));
  const set = (ext) => `img/${name}-${big}.${ext} ${big}w, img/${name}-${small}.${ext} ${small}w`;
  const load = opts.eager ? ' fetchpriority="high"' : ' loading="lazy"';
  return `<picture><source type="image/avif" srcset="${set('avif')}" sizes="${sizes}"><img src="img/${name}-${small}.webp" srcset="${set('webp')}" sizes="${sizes}" width="${w}" height="${h}" alt="${esc(alt)}"${load} decoding="async"></picture>`;
}

/* timeline of one session, derived from the stage data */
function timeline() {
  const s = H.stage, out = [];
  let m = 0;
  const add = (what, min, temp, cls) => { out.push({ what, from: m, to: m + min, temp, cls }); m += min; };
  add('Arrive, change, rinse', H.session.arrive, s.rest.temp, 'rest');
  for (let r = 1; r <= H.session.rounds; r++) {
    add(`Round ${r}: hot room`, s.hot.min, s.hot.temp, 'hot');
    add(`Round ${r}: rinse`, s.rinse.min, s.rinse.temp, 'rinse');
    add(`Round ${r}: cold plunge`, s.plunge.min, s.plunge.temp, 'plunge');
    add(`Round ${r}: rest room`, s.rest.min, s.rest.temp, 'rest');
  }
  add('Shower and dress', H.session.leave, s.rest.temp, 'rest');
  return out;
}
H.timeline = timeline();
const tl = H.timeline;
if (tl[tl.length - 1].to !== H.session.total) throw new Error(`timeline adds to ${tl[tl.length - 1].to}, session.total is ${H.session.total}`);

/* ---------- css/temps.css ---------- */
function tempsCss() {
  const temps = [...new Set([...H.PALETTE.map((p) => p.t), H.stage.rest.temp])].sort((a, b) => b - a);
  let css = '/* Generated by tools/build.mjs from js/hollin-data.js (HOLLIN.at). Do not edit by hand. */\n';
  for (const T of temps) {
    const a = H.at(T);
    const sel = T === 90 ? ':root, .t-90' : `.t-${T}`;
    css += `${sel} { --ground: ${a.ground}; --ground2: ${a.ground2}; --ink: ${a.ink}; --dim: ${a.dim}; --accent: ${a.accent}; --field: ${a.field}; --err: ${a.err}; --wdth: ${a.wdth.toFixed(1)}; --wght: ${Math.round(a.wght)}; --line: color-mix(in srgb, var(--ink) 16%, transparent); --line-strong: color-mix(in srgb, var(--ink) 42%, transparent); color-scheme: ${a.light ? 'light' : 'dark'}; }\n`;
  }
  return css;
}

