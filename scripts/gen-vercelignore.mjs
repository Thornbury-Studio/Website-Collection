#!/usr/bin/env node
/* Keep the PUBLIC bulk out of the Vercel deployment (it is served from Cloudflare instead, see vercel.json rewrites).
 * Rewrites only the block between the two markers in .vercelignore; every other line is left untouched.
 * The list comes from the build output folder so it can never drift from what was actually published.
 * usage: node scripts/gen-vercelignore.mjs <dist-public dir>
 */
import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';

const dist = resolve(process.argv[2] || '../dist-public');
if (!existsSync(join(dist, 'index.html'))) { console.error('not a build output folder:', dist); process.exit(1); }
const START = '# >>> cloudflare-public (generated by scripts/gen-vercelignore.mjs — do not edit by hand)';
const END = '# <<< cloudflare-public';

const lines = [];
for (const name of readdirSync(dist).sort()) {
  if (name === '_redirects') continue;                       // origin-only file, not part of the Vercel deploy anyway
  const p = join(dist, name);
  if (name === 'templates') {
    for (const slug of readdirSync(p).sort()) lines.push(statSync(join(p, slug)).isDirectory() ? `/templates/${slug}/` : `/templates/${slug}`);
  } else lines.push(statSync(p).isDirectory() ? `/${name}/` : `/${name}`);
}

const file = join(process.cwd(), '.vercelignore');
let text = readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
const block = `${START}\n${lines.join('\n')}\n${END}\n`;
const re = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\n?`);
text = re.test(text) ? text.replace(re, block) : text.replace(/\n*$/, '\n\n') + block;
writeFileSync(file, text);
console.log(`wrote ${lines.length} exclusion lines to .vercelignore`);
